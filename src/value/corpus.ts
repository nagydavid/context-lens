function cannedTransport(html: string, headers: Record<string, string> = { "content-type": "text/html" }): WebTransport {
  return async () =>
    ({
      status: 200,
      headers,
      body: (async function* () {
        yield Buffer.from(html);
      })(),
    }) satisfies WebTransportResponse;
}

